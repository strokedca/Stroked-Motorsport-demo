import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('isolated PostgreSQL workflow, authorization, validation and attendance',async()=>{
  const pg=new PGlite();
  try {
    await pg.exec(`create role anon;create role authenticated;create schema auth;
      create table auth.users(id uuid primary key,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create table public.event_admins(user_id uuid primary key,added_at timestamptz default now());
      create table public.stroked_v5_events(id uuid primary key default gen_random_uuid(),created_by uuid,payload jsonb,status text default 'pending',created_at timestamptz default now(),reviewed_at timestamptz,reviewed_by uuid,review_note text default '');
      create table public.stroked_v53_profiles(user_id uuid primary key,organization text,city text,region text,public_email text,website text,updated_at timestamptz default now());
      create table public.stroked_v54_rsvps(event_id uuid,user_id uuid,response text,guests integer,updated_at timestamptz default now(),primary key(event_id,user_id));
      create table public.stroked_v53_requests(id uuid primary key,event_id uuid,created_by uuid,payload jsonb,action text,status text,created_at timestamptz,reviewed_at timestamptz,reviewed_by uuid,review_note text);`);
    const id=n=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
    for(const n of [1,2,3,4,5])await pg.query('insert into auth.users values($1,$2,$3)',[id(n),n===4?null:new Date().toISOString(),{account_type:[1,3].includes(n)?'organizer':'rider'}]);
    await pg.query('insert into public.event_admins(user_id) values($1)',[id(5)]);
    const migration=await readFile(new URL('../supabase/migrations/20261111_v55_testing.sql',import.meta.url),'utf8');
    await pg.exec(migration);
    async function actor(n,sql,args=[]){await pg.exec('reset role');await pg.query("select set_config('request.jwt.claim.sub',$1,false)",[n?id(n):'']);await pg.exec(n?'set role authenticated':'set role anon');return (await pg.query(sql,args)).rows;}
    const call=async(n,name,args=[])=>{const placeholders=args.map((_,i)=>'$'+(i+1)).join(',');const fn='public.stroked_v55_'+name+'('+placeholders+')';const sql=['public_events','my_events','admin_events','admin_requests'].includes(name)?"select coalesce(jsonb_agg(f.value),'[]') as value from "+fn+' f(value)':'select '+fn+' as value';const rows=await actor(n,sql,args);return rows[0]?.value;};
    const deny=async(fn,pattern)=>assert.rejects(fn,pattern);
    const date=new Date(Date.now()+7*86400000).toISOString().slice(0,10);
    const payload={name:'V5.5 Test Ride',club:'Test Club',province:'PEI',city:'Charlottetown',date,categories:['Motorcycles'],status:'Scheduled',details:'Test event'};
    await deny(()=>call(null,'my_account'),/permission denied/);
    await deny(()=>call(4,'my_account'),/verified email/);
    assert.equal((await call(2,'my_account')).account_type,'rider');
    await deny(()=>call(2,'submit',[payload]),/organizer account/);
    await deny(()=>actor(2,'select * from stroked_v55_testing.admins'),/permission denied/);
    await deny(()=>call(2,'admin_events'),/Administrator only/);
    await pg.exec('reset role');await pg.query('update auth.users set raw_user_meta_data=$1 where id=$2',[{account_type:'organizer',is_admin:true},id(2)]);
    assert.equal((await call(2,'my_account')).account_type,'rider');
    assert.equal((await call(2,'my_account')).is_admin,false);
    await deny(()=>call(1,'submit',[{...payload,date:'2027-02-30'}]),/date|range/);
    await deny(()=>call(1,'submit',[{...payload,categories:null}]),/category/);
    const event=await call(1,'submit',[payload]);
    assert.equal((await call(null,'public_events')).length,0);
    await deny(()=>call(2,'review',[event,'approved','']),/Administrator only/);
    await deny(()=>call(3,'request_change',[event,payload,'edit']),/not yours/);
    await deny(()=>call(2,'save_rsvp',[event,'going',1]),/not available/);
    assert.equal(await call(5,'review',[event,'approved','']),true);
    assert.equal(await call(5,'review',[event,'approved','']),false);
    assert.equal((await call(null,'public_events')).length,1);
    await call(2,'save_rsvp',[event,'going',2]);await call(2,'save_rsvp',[event,'going',2]);
    let rows=await call(null,'public_events');assert.deepEqual(rows[0].counts,{going:1,guests:2,interested:0});
    assert.deepEqual(await call(2,'my_rsvp',[event]),{response:'going',guests:2});
    assert.equal(await call(3,'my_rsvp',[event]),null);
    await call(3,'save_rsvp',[event,'going',1]);
    rows=await call(null,'public_events');assert.deepEqual(rows[0].counts,{going:2,guests:3,interested:0});
    await call(2,'save_rsvp',[event,'interested',8]);
    rows=await call(null,'public_events');assert.deepEqual(rows[0].counts,{going:1,guests:1,interested:1});
    await deny(()=>call(2,'save_rsvp',[event,null,0]),/Invalid RSVP/);
    await deny(()=>call(2,'save_rsvp',[event,'going',11]),/Guests/);
    await deny(()=>call(null,'save_rsvp',[event,'going',0]),/permission denied/);
    await call(2,'save_rsvp',[event,'not_going',0]);assert.equal(await call(2,'my_rsvp',[event]),null);
    await deny(()=>call(2,'save_profile',[{organization:'Unauthorized'}]),/organizer account/);
    await call(1,'save_profile',[{organization:'Test Club',public_email:'public@example.test',website:'https://example.test'}]);
    rows=await call(null,'public_events');assert.equal(rows[0].organizer.public_email,'public@example.test');assert.equal(JSON.stringify(rows).includes(id(1)),false);
    const change=await call(1,'request_change',[event,{...payload,name:'Updated Test Ride'},'edit']);
    assert.equal((await call(null,'public_events'))[0].payload.name,payload.name);
    await deny(()=>call(1,'request_change',[event,payload,'edit']),/pending request/);
    await deny(()=>call(1,'review_request',[change,'approved','']),/Administrator only/);
    await call(5,'review_request',[change,'approved','']);assert.equal((await call(null,'public_events'))[0].payload.name,'Updated Test Ride');
    const cancellation=await call(1,'request_change',[event,payload,'cancel']);await call(5,'review_request',[cancellation,'approved','']);
    assert.equal((await call(null,'public_events'))[0].payload.status,'Cancelled');
    await deny(()=>call(2,'save_rsvp',[event,'going',0]),/not available/);
    await call(3,'save_rsvp',[event,'not_going',0]);assert.equal(await call(3,'my_rsvp',[event]),null);
    const own=await call(1,'my_events');assert.equal(own[0].id,event);assert.deepEqual(own[0].counts,{going:0,guests:0,interested:0});
    await call(2,'become_organizer');assert.equal((await call(2,'my_account')).account_type,'organizer');assert.equal((await call(2,'my_account')).is_admin,false);
    await pg.exec('reset role');assert.equal((await pg.query('select count(*)::int as n from public.stroked_v5_events')).rows[0].n,0);
    await pg.exec(migration);assert.equal((await call(1,'my_events')).length,1);
  }finally{await pg.close();}
});
